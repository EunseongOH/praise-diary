import { test, expect } from '@playwright/test';

test('F archive: minimal list, search modal, picker, independent pagination and restoration',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.addInitScript(()=>{
  const entries=Array.from({length:65},(_,i)=>{const entryDate=i<40?'2026-10-01':'2025-12-01';return {id:'archive-'+i,entryDate,createdAt:entryDate+'T12:'+String(i%60).padStart(2,'0')+':00Z',title:'기록 '+i,body:'나에게 건넨 용기 '+i}});
  const reflections=[{id:'r1',entryId:'archive-45',body:'다시 읽은 마음',reflectionDate:'2026-11-01',createdAt:'2026-11-01T00:00:00Z',updatedAt:'2026-11-01T00:00:00Z'}];
  sessionStorage.setItem('praise-diary:prototype:v1',JSON.stringify({entries,reflections,ideas:[],letterDrawUnlockedAt:'2026-11-01',boundaryHour:0,reducedMotion:true}));
 });
 await page.goto('/');
 await page.getByRole('button',{name:'내가 남긴 칭찬 보기'}).click();
 const base=page.locator('.archive-base'), rows=base.locator('.diary-row');
 await expect(rows).toHaveCount(30);
 await expect(page.getByRole('searchbox')).toHaveCount(0);
 await base.getByRole('button',{name:'더 보기',exact:true}).click();
 await expect(rows).toHaveCount(60);
 const target=rows.nth(45);
 const id=await target.getAttribute('data-entry-id');
 await target.scrollIntoViewIfNeeded();
 await target.click();
 await page.getByRole('button',{name:'뒤로가기',exact:true}).click();
 await expect(rows).toHaveCount(60);
 await expect(base.locator('.diary-row[data-entry-id="'+id+'"]')).toBeFocused();
 await base.getByRole('button',{name:'칭찬 검색하기'}).click();
 const overlay=page.getByRole('dialog',{name:'칭찬 검색',exact:true}),search=overlay.getByRole('searchbox',{name:'칭찬 검색'});
 await expect(search).toBeFocused();
 const field=overlay.locator('.ui-search-field .ui-field-shell');
 expect(await field.evaluate(el=>({radius:getComputedStyle(el).borderRadius,line:getComputedStyle(el,'::after').height,shadow:getComputedStyle(el).boxShadow}))).toEqual({radius:'0px',line:'2px',shadow:'none'});
 const initialField=await field.boundingBox();
 await search.blur();
 expect(await field.evaluate(el=>getComputedStyle(el,'::after').height)).toBe('1px');
 expect((await field.boundingBox())?.height).toBe(initialField?.height);
 await search.focus();
 await expect(page.locator('.archive-search-dim')).toBeVisible();
 await search.fill('용기');
 const results=overlay.locator('.diary-row');
 await expect(results).toHaveCount(30);
 await expect(results.first().locator('mark')).toContainText('용기');
 await expect(overlay.locator('.ui-list-section-header')).toHaveCount(0);
 await overlay.getByRole('button',{name:/기간 선택:/}).click();
 const picker=overlay.getByRole('dialog',{name:'기간 선택',exact:true});
 await expect(picker.locator('.ui-period-grid button')).toHaveCount(12);
 await picker.getByRole('button',{name:'연도 선택으로 전환'}).click();
 await picker.getByRole('button',{name:'2025년',exact:true}).click();
 await expect(picker.getByRole('button',{name:'2025년 12월',exact:true})).toBeEnabled();
 await picker.getByRole('button',{name:'2025년 전체',exact:true}).click();
 await expect(results).toHaveCount(25);
 const toggle=overlay.getByRole('button',{name:'마음이 담긴 칭찬'});
 const before=await toggle.boundingBox();
 await toggle.click();
 await expect(results).toHaveCount(1);
 await expect(toggle).toHaveAttribute('aria-pressed','true');
 expect((await toggle.boundingBox())?.width).toBe(before?.width);
 await results.first().click();
 await page.getByRole('button',{name:'뒤로가기',exact:true}).click();
 await expect(search).toHaveValue('용기');
 await expect(results).toHaveCount(1);
 await expect(results.first()).toBeFocused();
 await search.fill('없는 검색어');
 await expect(overlay.getByText('찾는 칭찬이 없어요.')).toBeVisible();
 await overlay.getByRole('button',{name:'검색 조건 초기화'}).click();
 await expect(search).toHaveValue('');
 await expect(page.locator('.archive-search-dim')).toBeVisible();
 for(const width of [320,360,390,430]){
  await page.setViewportSize({width,height:720});
  const period=overlay.getByRole('button',{name:/기간 선택:/});
  await expect(period.locator('svg')).toHaveCount(1);
  const a=await period.boundingBox(),b=await toggle.boundingBox();
  expect(await period.evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)');
  expect(Math.abs((a?.y??0)-(b?.y??0))).toBeLessThan(1);
  await period.click();
  await expect(picker).toBeVisible();
  expect((await period.boundingBox())?.width).toBe(a?.width);
  expect((await toggle.boundingBox())?.x).toBe(b?.x);
  expect(await period.evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)');
  expect(await picker.evaluate(el=>el.getBoundingClientRect().right<=innerWidth)).toBeTruthy();
  await page.keyboard.press('Escape');
  await expect(picker).toHaveCount(0);
  await expect(overlay).toBeVisible();
 }
 await expect(page.locator('select,datalist,dialog')).toHaveCount(0);
 await overlay.getByRole('button',{name:'검색 닫기'}).click();
 await expect(overlay).toHaveCount(0);
 await expect(base.getByRole('button',{name:'칭찬 검색하기'})).toBeFocused();
 await expect(rows).toHaveCount(60);
});
